с той же историей, что и белый, получал в 2 раза больше шансов быть 
признанным «опасным». 
Это не случайность. Это производная от данных, на которых обучались 
алгоритмы: 
- данные об арестах – но арестуют чаще именно чернокожих (не 
потому, что они больше преступны, а потому что патрулируют их районы 
чаще); 
- данные о вызовах полиции – но вызовы зависят от поведения 
соседей и отношений с правоохранителями; 
- данные о судимостях – но они не включают оправдательные 
приговоры, хотя они есть. 
