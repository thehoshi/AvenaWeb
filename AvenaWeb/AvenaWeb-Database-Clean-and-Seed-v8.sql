Вильгельм фон Гумбольдт

Позже идею Гумбольдта развили американские лингвисты Эдвард Сепир и Бенджамин Уорф. Именно они создали гипотезу лингвистической относительности, которая по сей день изучается учёными. Их гипотеза объясняет, почему люди, говорящие на разных языках, могут по-разному воспринимать цвета или время.

Например, в русском языке есть отдельные слова для синего и голубого цветов, а в английском языке есть только одно слово для обоих оттенков - blue.  Именно поэтому носители русского языка могут различать цвета быстрее, чем носители английского. «(Winawer et al., 2007, PNAS, 4, 7780-7785)»  
Однако не стоит переоценивать этот эффект : попытка воспроизвести это исследование в 2020 году (проект Abeerdeen, журнал Cognition), показала, что влияние языка на различие цветов гораздо скромнее и меньше чем в оригинальном эксперименте. Это говорит о том, что эффект не столь однозначен как казалось изначально.

Также язык может влиять на восприятие ответственности. В разных языках разное отношение к агентивности. В английском или русском языке чаще используется активный залог («человек разбил телефон»), в то время как в испанском часто используется пассивный залог («телефон разбился»). Исследования показывали, что носители испанского языка, благодаря грамматике, реже склонны обвинять людей в непреднамеренных происшествиях, чем носители английского (Fausey & Boroditsky, 2010). Однако и здесь важна научная осторожность: язык — лишь один из факторов, наряду с культурными особенностями.

Грамматика языка также может влиять на восприятие некоторых вещей. Например в испанском языке слово мост (puente) - мужского рода, поэтому носители описывают его как «крепкий» и «надежный». В немецком языке мост (brücke) - женского рода, и носители описывают его как «изящный» и «красивый». Это доказывает что даже язык может формировать наши ассоциации с предметами.Boroditsky, L., & Schmidt, L. A. (2000). Sex, syntax, and semantics.

Ещё один яркий пример — это восприятие времени. У австралийских аборигенов (например, из сообщества Pormpuraaw) нет слов «лево» и «право». Они используют абсолютную систему координат по сторонам света (север, юг, восток, запад). Исследование Леры Бородицки и Элис Гэби (2010) показало, что аборигены не просто отлично ориентируются в пространстве, но и воспринимают время через эту призму. Они раскладывают хронологические события (например, карточки с картинками) не слева направо, как это делаем мы, а строго с востока на запад, в зависимости от своего положения в данный момент (Boroditsky, L., & Gaby, A., 2010. Remembrances of times East: Absolute spatial representations of time in an Australian aboriginal community).

