ВВЕДЕНИЕ

В эпоху цифровых технологий социальные сети стали неотъемлемой частью повседневной жизни, но вместе с удобством они принесли и новые психологические вызовы. Большое количество экранного времени и постоянная проверка уведомлений приводят к недосыпу, отсутствию внимания и фокуса.

Стремление быть «в курсе всего» нередко оборачивается тревогой, ощущением нехватки времени и чувством неудовлетворённости собственной жизнью. Анализ механизмов формирования FOMO и стратегий обретения JOMO позволяет больше осмыслить влияние соцсетей на состояние человека и выработать способы сохранения психологического равновесия в цифровом мире.

Цель исследования - выяснить по какой причине в нынешнее время множество людей страдают из-за тревоги и являются ли соцсети источником этого.

ОСНОВНАЯ ЧАСТЬ

Обзор литературы

Зависимость от социальных сетей.

Зависимость от телефона и социальных сетей – это состояние, при котором человек не может контролировать экранное время, появляется желание постоянно проверять новые сообщения, тренды и новые посты других людей; Концентрация и фокус на длительное время снижается, или пропадает совсем, возникает тревожность от отсутствия интернета и связи.

Есть несколько причин появления социальной зависимости:

Быстрый дофамин:  в состоянии скуки, стресса, ожидании и пр., мозгу необходимо снизить стресс или заняться чем-то. Самое простое – полистать ленту соцсетей.

Избегание реальной жизни: в моменты грусти или эмоционального выгорания человек хочет «спрятаться» от внешнего мира и социализации, именно поэтому он хватается за телефон.

Социальное одобрение: положительные реакции и комментарии вызывают приятные чувства у людей. Желание повторно получить похвалу от других пользователей заставляет человека проводить все больше времени в интернете.

Высокий темп обработки информации: многофункциональные платформы, в которых можно выполнять несколько действий одновременно (слушать музыку и читать статью, например) задают мозгу быстрый темп обработки информации, что, в последствии, вызывает желание потреблять больше контента.

Почему после просмотра соцсетей плохое настроение?

Многие люди замечают, что после длительного просмотра социальных сетей у них резко ухудшается настроение. Это связано с информационной перегрузкой, сравнением своей жизни с жизнью других, временем, проведенным за просмотром телефона, недосыпом.

Например, пользователь интернета часто видит в ленте негативные новости, и чем больше он их читает, тем больше алгоритмы показывают ему похожие посты. В последствии вся эта информация остается в памяти, человек постоянно думает про это, и его настроение портится.

Другой пример: просмотр соцсетей перед сном препятствует выработке гормона мелатонина (гормон сна), из-за чего человек не высыпается и на следующий день чувствует постоянную усталость.

В интернете свойственно показывать яркие и успешные картинки. Зрители подобного контента ловят себя на мысли: «у меня не такая интересная жизнь», «я бы хотел(а) быть как он(а)». Самооценка и, в последствии, настроение ухудшаются, а уровень стресса возрастает.

Феномен «FOMO»

Феномен FOMO (от англ. fear of missing out ) впервые был упомянут американским капиталистом и писателем Патриком Макгиннисом в 2004 году. «Fear of missing out», или «Страх упустить что-то важное» - это ощущение тревоги, которое возникает при мысли, что где-то происходит что-то более важное и интересное, а ты в этом не участвуешь.

Самое яркое проявление FOMO можно заметить в маркетинге. Искусственно созданные акции и распродажи, например, «Черная пятница», скидки с лимитом по времени заставляют людей покупать даже то, что им на самом деле не нужно. Когда мы видим надписи вроде «Скидка 50% только 3 часа», в нас просыпается страх упустить выгоду. Кажется, что если не купим сейчас, то будем жалеть потом, поэтому такие предложения заставляют действовать импульсивно.

Но это не единственное проявление FOMO. Как правило, у подростков FOMO проявляется в частой проверке уведомлений и нуждой постоянно быть «онлайн». Страх упустить новый тренд, новость или просто уведомление от друга превращается в тревогу: большинство ребят постоянно держат телефон при себе, а порой даже засыпают с гаджетом в руке.

Психологи, проводя исследования, выявили: у подростков, которые проверяют свой смартфон очень часто, повышенный уровень FOMO. Более того, страх упустить что-то важное приводит к выделению гормонов стресса, таких как кортизол, что в последствии плохо влияет на качество сна.

1.4 Феномен «JOMO»

Абсолютно противоположный эффект наблюдается от JOMO (от англ. joy of missing out ), то есть радость от того, что вы что-то пропустили. В исследовании А. Тандора и соавторов, JOMO описывается как защитный механизм психики.

Люди, практикующие JOMO хотят добиться эффекта, когда телефон приносит человеку только пользу. Наиболее мягкой формой является отключение уведомлений и ввод лимита экранного времени. В более жесткой версии, люди используют телефон всего несколько минут в течение дня.

Участники онлайн сообществ делятся своим опытом и советами, показывая, как этот опыт значительно улучшил качество их жизни, например: “Отказ от соцсетей принёс больше пользы для моего психического здоровья, чем я ожидал” (Reddit,  2025). Внешняя  группа пользователей, остающихся в логике FOMO, служит контрастным примером для них.

Вред смартфона после пробуждения

Исследования психологов показали: около 80% людей проверяют новые уведомления в течении 15-ти минут после пробуждения. Это очень вредно для организма, ведь когда мы смотрим ленту соцсетей или электронную почту, мозг выделяет большое количество дофамина – нейровещество, которое заставляет вас чувствовать себя награжденным и проводить в смартфоне больше времени.

Более того, проверяя телефон сразу после пробуждения, мы концентрируемся на том, что мы видим, а не на наших ощущениях. То есть, контент, потребляемый утром задает настроение, продуктивность и фокус на день.

1.6 Польза смартфона

Безусловно, телефон – незаменимый помощник в жизни человека. В интернете ученики и студенты могут мгновенно найти какую-либо информацию или учебные материалы. Социальные сети помогут вдохновиться, а с помощью мессенджеров можно оставаться на связи.

Как избавится от телефонной зависимости

Исходя из результатов опроса, проведенного во время исследования, большинство пользователей смартфона хотели бы уменьшить свое экранное время.

Вот несколько вещей, которые советуют психологи, чтобы снизить экранное время и, вместе с этим, тревожность, недосыпания и плохое настроение:

Для начала, попробуйте поставить лимит времени на приложения. С каждым днем уменьшайте количество времени, проведенного за соцсетями.

Вы не обязаны постоянно быть в сети и сиюминутно отвечать на сообщения. Выделите 60-120 минут в день, когда вы не будете проверять и отвечать на сообщения. Потратьте это время на себя, займитесь чем-то, что улучшит вас.

Во время работы, учебы или занятия, на котором нужно сосредоточиться, выключайте уведомления на телефоне и относите его в другую комнату. Так вам будет не на что отвлекаться.

Если телефон нужно держать при себе, но вы слишком часто на него отвлекаетесь, попробуйте положить на него необычный предмет (например, игрушку, бутылку или пенал). Это поможет вам осознать момент, когда вы тянетесь к телефону. Проанализируйте, почему вы захотели взять телефон? Возможно, мозг избегает сложных задач или ему просто скучно.

Выделите день, когда вы не будете пользоваться смартфоном. Этот пункт лучше практиковать, когда ваше экранное время снизится до желаемого, то есть, не сразу. Это разнообразит вашу рутину, а мозг отдохнет от экрана и информационного шума.

