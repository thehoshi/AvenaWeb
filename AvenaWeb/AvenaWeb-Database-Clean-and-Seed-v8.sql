интерпретируется в каждом государстве по-своему, создавая уникальные методы и практики. 
       В китайской системе образования внимания уделяется традиционным игровым формам (диаболо, 
цзяньцзы, сянци, го, маджонг) и инновациям, таким как кратковременный дневной сон на уроках и 
интерактивные таблички для мгновенной обратной связи.  
       В Японии акцент сделан на возрождении каллиграфии (сёдо) и на логико-числовых задачах (кенкен), 
развивающих координацию, терпение и аналитическое мышление.  
       В Корее представлены методы развития речевых навыков и памяти: shadow reading, интервальное 
повторение, визуальные конспекты и gongbang, а также использование цифровых инструментов для 
поддержки запоминания.  
       В Сингапуре рассматривается системный набор из более чем 250 активных методов, направленных 
на развитие четырех ключевых навыков: коммуникации, сотрудничества, критического мышления и 
креативности, включая принципы самостоятельного освоения материала, кооперативные формы 
обучения и управляемые сигналы внимания. 
       Заключение подчеркивает схожесть целей — уход от простой передачи знаний к развитию 
мышления и самоуправления. 
 
                                                                                   Введение 
 
       Образование долгие годы играет важную роль во взаимоотношениях между людьми и в жизни 
человека в целом. В прошлых столетиях учиться грамоте могли люди, чей статус соответствовал 
требованиям образовательного учреждения, например в церкви, где образование зависело от 
социального статуса учащихся и от уровня подготовки преподавателей. В настоящее время учеба 
является главной обязанностью каждого ребенка, а обучение в государственной школе –– бесплатное. 
Сейчас детям трудно сосредоточиться на уроках, а способность удерживать внимание является одной из 
важнейших составляющих успешного обучения. Учителя из разных стран используют различные 
методы повышения концентрации внимания учащихся. Особенно интересен опыт восточной Азии, 
образовательные системы которых регулярно занимают высокие позиции в международных 
исследованиях качества образования. К примеру, по версии рейтинга PISA [12], Школьники из 
Сингапура признаны лучшими в мире. В 2023 году помимо Сингапура сильные результаты показали 
китайский анклав Макао, Тайвань, Япония и Южная Корея. В этой статье мы расскажем об одних из 
самых эффективных методов удержания внимания некоторых стран Азии, проведем анализ методов,  
сравним их и дадим рекомендации. 
                                                                             Основная часть 
 
       Образовательные системы стран Азии привлекают внимание исследователей и педагогов со всего 
мира, поскольку они отличаются высокой эффективностью и необычными подходами к организации 
учебного процесса. На первый взгляд может создаться впечатление, будто их объединяют высокий 
уровень учебных результатов, строгая дисциплина и уважительное отношение к учителю. Однако в 
каждой стране этого региона есть свои собственные методики, которые совмещают культурные 
традиции с современными требованиями общества.  
 
          Фундаментальное сходство образовательных подходов в азиатских странах таится в 
конфуцианской традиции, которая формирует отношение к учению как к процессу непрерывного 
самосовершенствования. Однако каждая страна интерпретирует эту основу по-своему, что различает

подходы к обучению и создает уникальные  методики, которые используются по всему миру, как одни 
из самых эффективных и удобных. 
 
                                                                                     В Китае 
 
       В китайской системе образования хорошо видно, как древние игровые формы сочетаются с 
современными методиками преподавания [1]:  
–– Диаболо (от 3 до 8 лет) развивает концентрацию внимания и координацию движений, позволяя детям 
играть как индивидуально, так и в парах в течение 10-15 минут. 
–– Цзяньцзы (от 5 до 12 лет) тренирует баланс и реакцию в групповом формате — от 2 до 30 участников, 
продолжительностью 15–20 минут. 
–– Сянци (китайские шахматы, от 7 до 15 лет) развивает тактическое мышление и, согласно некоторым 
исследованиям, повышает математические навыки. 
–– Го — древнейшая игра (более 4000 лет), рекомендуемая для детей от 8 лет и старше. Партии длятся 
45-90 минут и развивают стратегическое мышление, а также, как по мнению ряда исследований, игра 
способствует развитию стратегического мышления, которое может быть полезна при изучении 
программирования и инженерных наук.  
–– Маджонг (от 9 лет, 60-90 минут, группы по 4 человека) совершенствует гибкость мышления и память. 
       
       Азиатские страны успешно совмещают вековые традиции с передовыми технологиями 
современности. 
       Китай предлагает несколько нестандартных решений. Одна из самых резонансных практик — 
кратковременный сон на уроках [2]. Школьникам предоставляется возможность отдохнуть около 20 
минут, в частности  после обеда. Эта практика основана на научных исследованиях, подтверждающих, 
что короткий сон (15-20 минут) положительно влияет на внимание, когнитивные функции и 
продуктивность. За это время мозг успевает восстановиться, благодаря чему учащиеся становятся  более 
сосредоточенными. 
       Другая китайская инновация — интерактивные задания с использованием табличек [3]. Три четверти 
урока отводится на выполнение интерактивных упражнений, в которых задействован весь класс, и лишь 
четверть времени — на самостоятельную работу. При ответе на задачу дети поднимают таблички со 
своими ответами, и педагог сразу видит, кто не справился. Это простейший способ обратной связи, 
позволяющий учителю отслеживать усвоение материала в реальном времени. 
       В школьной практике традиционные игры занимают значимое место. Их рассматривают не просто 
как способ развлечься, а как элемент учебного процесса, который способствует развитию 
познавательных навыков. В этом и проявляется китайский взгляд на обучение как на действие, 
основанное на практике. 
                                                                                    В Японии 
 
      В Японии акцент сделан на обращении к традиционным видам искусства. В стране приняли решение 
вновь ввести в школьную программу сёдо, то есть обучение каллиграфии, известной как "путь письма" 
[4]. Такие занятия помогают детям точнее управлять движениями пальцев, лучше координировать 
зрение и руки, а кроме того, формируют аккуратность, самостоятельность,  сосредоточенность и 
внимательность. По мнению японских педагогов, каллиграфия благотворно влияет на общую 
успеваемость, поскольку развивает терпение и дисциплину мышления. 
       Япония также предлагает математическую игру кенкен — сетку с цифрами, где строки и столбики 
должны содержать полный набор неповторяющихся цифр [5]. В блоках, обведенных жирной линией, 
указаны арифметические действия (сложение, вычитание, умножение, деление), и при применении этого 
действия ко всем цифрам в блоке должно получиться число в левом верхнем углу. Эта игра тренирует 
логическое мышление и вычислительные навыки. 
     Существует еще одна японская методика поддержания концентрации внимания дзасин [6], она 
предназначена для подростков и взрослых. Эта практика культивирует два качества, которых нам не 
хватает в повседневной жизни: спокойствие и сосредоточенность. Почти 50% времени в бодрствующем 
состоянии мы думаем не о том, что происходит здесь и сейчас. Но мы так привыкли к рассеянным 
мыслям, что даже не замечаем, как много их у нас в голове. Чтобы войти в дзасин, нужно:

– отказаться от многозадачности. Когда вы беретесь за одну задачу и тут же начинаете думать о другой, 
вы сигнализируете мозгу, что первая задача наполовину выполнена, а значит, требует меньше внимания. 
Чем больше задач вы решаете одновременно, тем меньше внимания вы им уделяете;  
– сосредоточиться на процессе движения, а не на том, что даст вам его достижение; 
– не завышать амбиции, которые мешают видеть реальные задачи и реальные достижения. Реальные 
задачи теряются на фоне грандиозной конечной цели, с которой мы их сравниваем. Однако вам следует 
мысленно разбить самый амбициозный проект на составные части, и вы увидите, что каждая из них не 
будет отличаться от самой обыденной задачи; 
– не терять бдительность, даже когда вам кажется, что все проблемы решены. Умение не торопить 
события и уделять равное внимание каждому моменту – важный навык в жизни любого человека; 
 
                                                                              В Южной Корее 
 
      Южная Корея известна своими методиками развития речи и эффективного запоминания. Shadow 
reading [7] (чтение в режиме эхо) создает мощные нервные синапсы, ускоряющие формирование 
речевых автоматизмов. Дети начинают говорить быстрее и увереннее уже через месяц практики. 
Рекомендуемый возраст — от 6 лет, продолжительность — от 10 минут. 
       Корейские школьники также активно применяют повторение с интервалами:  вместо зубрежки 
материала за один вечер они повторяют его в разные дни с обязательными перерывами, что позволяет 
информации перейти из кратковременной памяти в долговременную. Для этого используются 
приложения Anki или Quizlet. 
       Визуальные конспекты — еще один корейский подход: ученики оформляют записи с цветными 
заголовками, схемами, стрелками и наклейками, что помогает лучше понять материал и делает 
запоминание более приятным для визуалов. Эта практика популярна не только в Азии –– ею пользуются 
многие учащиеся со всего мира. 
       В Корее также известен термин нунчи [8]. В современном контексте нунчи означает способность 
чувствовать настроение собеседника или группы, быстро оценивать ситуацию, предугадывать ожидания 
других людей и соответствовать социальным нормам. Нунчи строится на нескольких важных 
принципах:  
1. Наблюдательность: человек с развитым нунчи внимательно следит за окружающими, подмечает 
малейшие изменения эмоций, выражений лица, жестов и интонаций.  
2. Молчаливое слушание: корейцы верят, что нунчи невозможно развить, если говорить больше, чем 
слушать. Тишина помогает услышать не только слова, но и то, что осталось невысказанным: эмоции, 
напряжение или скрытые ожидания. 
3. Адаптивность: нунчи – это гибкость в поведении, изменение собственной коммуникации в 
зависимости от ситуации. 
4. Уважение к иерархии и статусу: в корейском обществе нунчи тесно связан с уважением к старшим и 
вышестоящим по рангу. 
       Нунчи помогает и в учебе: когда учитель замечает, что ребенок нерешительно отвечает, он может 
задать ученику другой вопрос или вне урока повторно объяснить тему, которую ребенок не понял.  
       Наконец, совместная учеба (gongbang) — формат, в котором люди учатся в реальном времени 
(вживую или онлайн) [9]. Кто-то смотрит видеоурок, а кто-то объясняет тему, в которой разобрался. 
Получается, что и ученики узнают что-то новое, и тот, кто рассказывает, лучше запоминает материал. 
 
                                                                                 В Сингапуре 
 
       Сингапур выделяется среди азиатских стран своей передовой методикой, насчитывающей более 250 
приемов. Эта система, направлена на развитие четырех ключевых навыков: коммуникации, 
сотрудничества, критического мышления и творческого потенциала. 
Основные принципы сингапурской методики [10]: 
- Развитие самостоятельности: педагог делает упор на то, что дети способны самостоятельно усваивать 
новую информацию. При работе в парах они меняются ролями: один выступает в роли учителя, другой – 
ученика. Учитель лишь слушает их ответы и исправляет ошибки, если они есть, а ребенок учится 
действовать по заданному плану.

- Manage Mat: распределение учеников и управление сформированными группами [11]. 
Для проведения занятия учебные парты соединяются по две, формируя своеобразный квадрат. 
Рассаженные за этим столом четыре ученика, получают индивидуальные номерные и буквенные 
обозначения. Цифр, соответственно, четыре, а букв всего две: A и B.  
Смысл в том, что у каждого ученика есть две пары: одна –– это ученик и сосед, сидящий рядом (партнер 
по плечу), вторая –– ученик и сосед напротив (партнер по лицу). По ходу занятия ученики работают в 
разных парах или обобщенной командой. При таком подходе ребята самостоятельно изучают новый 
материал, при этом роль учителя по очереди берет на себя каждый из участников команды. Педагог же в 
данном случае следит за порядком, дает задания и подводит итоги урока. 
- Tic-Tac-Toe: метод формирует критическое мышление и изобретательность. Из подготовленной схемы 
ребята должны взять три слова и составить с ними предложения. При этом, все слова должны 
находиться в одном ряду: по горизонтали, вертикали или диагонали. 
- Quiz-Quiz-Trade: раздаются карточки с подготовленными вопросами и ответами к ним. Учащиеся 
должны проверить знания друг друга, пояснить непонятные моменты и поменяться карточками. 
- Rally Robin: работа в паре: обмен списком коротких ответов между двумя участниками. 
Обратим внимание, что дети приучаются работать по определенному алгоритму выполнения действий 
по команде. 
 
                                                                      Сравнительный анализ 
 
                                                                                                                                                                      (рис. 1) 
 
       Китайские методы схожи между собой тем, что концентрация развивается не через принуждение, а 
через игровую деятельность. Большинство упражнений требуют постоянной мозговой активности и 
принятия решений, поэтому внимание удерживается естественным образом. 
       Японские методики делают уклон в сторону размеренности и сосредоточенности, что помогает 
удерживать внимание на определенных аспектах, тренирует мозг спокойно принимать решения и 
развивает логическое мышление, которое может пригодиться в нестандартных ситуациях. 
       Корейские методы объединяются тем, что поддержание концентрации внимания происходит через 
визуализацию учебного материала и развитие коммуникабельности за счет правильно поставленной 
речи, внутренних рассуждений и понимания собеседника. Эти упражнения требуют постоянного 
наблюдения, что способствует долгому удержанию внимания на определенном объекте изучения или 
человеке, которого хотим понять.  
     Сингапурские методики аналогичны между собой тем, что тренируют самостоятельность, 
критическое мышление и изобретательность. Большинство методов требуют самостоятельного изучения 
материала и изобретать индивидуальные методы подхода к каждому человеку для объяснения темы, за 
счет этого внимание удерживается на предмете изучения и тема уясняется гораздо лучше и эффективнее. 
 
