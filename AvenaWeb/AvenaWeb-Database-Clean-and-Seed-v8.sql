«предупреждение» можно рассматривать как профилактику, то задержание – 
это уже мера принуждения, ограничивающая свободу. И здесь возникает 
вопрос: какое право даѐт государству вероятность? 
По действующему административному законодательству большинства 
стран, основание для задержания – наличие достаточных данных полагать, 
