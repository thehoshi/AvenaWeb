«совершило». Прошедшее время. Настоящее длительное. Но не будущее. 
Когда законодатель писала эти нормы, он не предусматривал, что 
«данными» могут быть три процента, выданные нейросетью. Если мы 
разрешаем прогноз как основание, мы молчаливо переопределя ем само 
понятие «правонарушение» – от действия к тенденции. 
