Основная часть

Вопрос о том, насколько язык влияет на  наше сознание, волнует философов и учёных уже не одно столетие. В данной статье мы разберём, как развивалась эта идея от трудов Вильгельма фон Гумбольдта до современных исследований , и на конкретных примерах попытаемся понять, может ли родная речь человека влиять на его восприятие времени, цвета, пространства и ответственности.

Первым кто сформировал мысль о связи языка и мышления считается немецкий учёный Вильгельм фон Гумбольдт. Он утверждал, что «язык, есть орган, образующий мысль» «О различии строя человеческих языков и его влиянии на духовное развитие человечества» (1830–1835).

