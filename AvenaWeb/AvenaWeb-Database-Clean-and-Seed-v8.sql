ЗАКЛЮЧЕНИЕ

Хотя смартфон является полезным инструментом, его неумеренное использование может негативно влиять на психологическое состояние и качество жизни подростков. Соблюдение баланса и использование стратегий снижения экранного времени могут помочь избежать негативных последствий.

