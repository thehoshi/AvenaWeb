агрегируют: 
- кредитную историю; 
- частоту и характер контактов с полицией (включая остановки, 
которые не привели к обвинению); 
- данные с камер распознавания лиц;

- мобильные геоданные (посещение определѐнных районов); 
- психоэмоциональные характеристики, извлечѐнные из постов в 
соцсетях. 
